// Rebuild sparse contact probes if the GLB geometry or authored poses change.
import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import * as THREE from 'three';
import {GLTFLoader} from 'three/addons/loaders/GLTFLoader.js';
import {RunnerAnimation} from '../src/runner-animation.js';
import {RunnerController} from '../src/controller.js';

const bytes=await readFile(new URL('../assets/nailong-rounded.glb',import.meta.url)),size=bytes.readUInt32LE(12);
const doc=JSON.parse(bytes.subarray(20,20+size));
doc.buffers[0].uri=`data:application/octet-stream;base64,${bytes.subarray(28+size).toString('base64')}`;
for(const mesh of doc.meshes)for(const primitive of mesh.primitives)delete primitive.material;
globalThis.ProgressEvent??=class{constructor(type,properties){Object.assign(this,properties);}};
const gltf=await new GLTFLoader().parseAsync(JSON.stringify(doc),'');
const animator=new RunnerAnimation(gltf.scene,gltf.animations),meshes=[],probes={},point=new THREE.Vector3();
gltf.scene.traverse(node=>{if(node.isSkinnedMesh){meshes.push(node);probes[node.name]=new Set();}});
function sample(){
  // Probe collection uses the unlifted pose; model-level contact correction
  // does not affect which geometry vertex is lowest.
  gltf.scene.updateMatrixWorld(true);
  for(const mesh of meshes){
    mesh.skeleton.update();let low=Infinity,index=0;
    for(let vertex=0;vertex<mesh.geometry.attributes.position.count;vertex++){
      mesh.getVertexPosition(vertex,point).applyMatrix4(mesh.matrixWorld);
      if(point.y<low){low=point.y;index=vertex;}
    }
    probes[mesh.name].add(index);
  }
}
for(const clip of gltf.animations)for(let frame=0;frame<=60;frame++){
  const time=clip.duration*frame/60;
  animator.reset({action:clip.name,actionTime:time,slideFromDive:clip.name==='Slide',distance:time*8.8});sample();
}
const runner=new RunnerController();runner.start();runner.course.clear();runner.course.nextFrontDistance=Infinity;animator.reset(runner);
const events=[[.15,'slide'],[.5,'jump'],[.75,'slide'],[1.25,'jump'],[1.5,'slide']];let event=0;
for(let frame=0;frame<336;frame++){
  if(event<events.length&&runner.elapsed>=events[event][0]-1e-8){runner.input(events[event++][1]);animator.update(runner,0);}
  runner.update(1/120);animator.update(runner,1/120);sample();
}
// Interrupt the entering, holding and recovering slide poses at varied phases.
for(const age of [.02,.08,.15,.4,.68,.78,.84]){
  animator.reset({action:'Slide',actionTime:age,distance:0,actionSerial:0});
  for(const [action,time] of [['Jump',.05],['Dive',.45],['Slide',.2],['Run',0]]){
    for(let frame=0;frame<=12;frame++){
      animator.update({action,actionTime:time,slideFromDive:action==='Slide',distance:time*8.8},frame===0?0:1/120);sample();
    }
  }
}
const contactIndices=Object.fromEntries(Object.entries(probes).map(([name,indices])=>[name,[...indices].sort((a,b)=>a-b)]));
const hash=createHash('sha256').update(bytes).digest('hex');
await writeFile(new URL('../src/animation-contacts.js',import.meta.url),
  `// Generated by tools/prepare_animation_contacts.mjs from the actual skinned model.\nexport const CONTACT_MODEL_SHA256='${hash}';\nexport const ANIMATION_CONTACTS=Object.freeze(${JSON.stringify(contactIndices)});\n`);
console.log(JSON.stringify({sha256:hash,probes:Object.fromEntries(Object.entries(contactIndices).map(([name,indices])=>[name,indices.length]))}));
